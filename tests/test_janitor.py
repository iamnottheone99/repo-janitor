def test_maintainer_creates_verified_branches_in_isolated_worktrees(
    sample_git_repo: Path,
) -> None:
    """Verify docstrings, README, and unit tests are committed to isolated janitor/* branches."""
    cfg = JanitorConfig(max_retries=2)
    fake_llm = FakeOllamaLLM(fail_first_test_attempt=True)
    maintainer = RepoMaintainer(sample_git_repo, config=cfg, llm=fake_llm)

    summary = maintainer.run_all()
    assert summary.committed_count == 3
    assert summary.failed_count == 0
    # Ensure self-healing retry occurred on unit test generation
    assert fake_llm.test_calls == 2

    branches = maintainer.worktrees.list_janitor_branches()
    branch_names = {b["branch"] for b in branches}
    assert "janitor/docs/math_ops" in branch_names
    assert "janitor/docs/readme-sync" in branch_names
    assert "janitor/tests/math_ops-add" in branch_names

    # Main working tree should remain untouched on the initial commit
    main_source = (sample_git_repo / "src" / "calc" / "math_ops.py").read_text(encoding="utf-8")
    assert "Autogenerated docstring" not in main_source


