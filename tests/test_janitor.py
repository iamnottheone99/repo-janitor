def test_inject_docstring_into_source() -> None:
    """Verify AST docstring injection preserves code and adds PEP 257 docstring."""
    raw = "def greet(name: str) -> str:\n    return f'Hello {name}'\n"
    updated = inject_docstring_into_source(raw, "greet", "greet", "Return a greeting.")
    assert '"""Return a greeting."""' in updated
    assert "return f'Hello {name}'" in updated


def test_scanner_detects_missing_docstrings_and_untested_functions(
    sample_git_repo: Path,
) -> None:
    """Verify RepoScanner identifies undocumented and uncovered functions."""
    scanner = RepoScanner(sample_git_repo)
    report = scanner.scan()

    assert report.total_files == 2
    assert len(report.missing_docstrings) == 1
    assert report.missing_docstrings[0].qualified_name == "add"
    assert len(report.untested_functions) == 1
    assert report.untested_functions[0].qualified_name == "add"
    assert report.readme_needs_update is True
    assert "math_ops" in report.readme_missing_modules


def test_maintainer_creates_verified_branches_in_isolated_worktrees(
    sample_git_repo: Path,
) -> None:
    """Verify docstrings, README, and unit tests are committed to isolated janitor/* branches."""
    cfg = JanitorConfig(max_retries=2)
    fake_llm = FakeOllamaLLM(fail_first_test_attempt=True)
    maintainer = RepoMaintainer(sample_git_repo, config=cfg, llm=fake_llm)

    summary = maintainer.run_all()
    assert summary.committed_count == 3
    assert summary.failed_count == 0
    # Ensure self-healing retry occurred on unit test generation
    assert fake_llm.test_calls == 2

    branches = maintainer.worktrees.list_janitor_branches()
    branch_names = {b["branch"] for b in branches}
    assert "janitor/docs/math_ops" in branch_names
    assert "janitor/docs/readme-sync" in branch_names
    assert "janitor/tests/math_ops-add" in branch_names

    # Main working tree should remain untouched on the initial commit
    main_source = (sample_git_repo / "src" / "calc" / "math_ops.py").read_text(encoding="utf-8")
    assert "Autogenerated docstring" not in main_source


def test_maintainer_discards_branch_when_verification_fails(
    sample_git_repo: Path,
) -> None:
    """Verify failing tests inside worktree never leave broken branches behind."""
    cfg = JanitorConfig(max_retries=1)
    broken_llm = FakeOllamaLLM(always_fail_tests=True)
    maintainer = RepoMaintainer(sample_git_repo, config=cfg, llm=broken_llm)

    summary = maintainer.run_unit_test_tasks()
    assert summary.committed_count == 0
    assert summary.failed_count == 1
    assert maintainer.worktrees.list_janitor_branches() == []
