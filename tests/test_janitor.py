class FakeOllamaLLM:
    """Deterministic fake LLM for testing isolated worktree maintenance flows."""

    def __init__(self, fail_first_test_attempt: bool = False, always_fail_tests: bool = False) -> None:
        self.fail_first_test_attempt = fail_first_test_attempt
        self.always_fail_tests = always_fail_tests
        self.test_calls = 0

    def generate_docstring(self, symbol: CodeSymbol) -> str:
        return f"Autogenerated docstring for {symbol.qualified_name}."

    def generate_unit_test(
        self,
        symbol: CodeSymbol,
        module_import_path: str,
        full_file_source: str,
        previous_error: str | None = None,
    ) -> str:
        self.test_calls += 1
        if self.always_fail_tests or (self.fail_first_test_attempt and self.test_calls == 1):
            return (
                f"from {module_import_path} import {symbol.symbol_name}\n\n"
                f"def test_{symbol.symbol_name}_broken():\n"
                f"    assert False, 'intentional failure'\n"
            )
        return (
            f"from {module_import_path} import {symbol.symbol_name}\n\n"
            f"def test_{symbol.symbol_name}_generated():\n"
            f"    assert {symbol.symbol_name}(2, 3) == 5\n"
        )

    def generate_readme_section(
        self,
        existing_readme: str,
        missing_modules: list[str],
        module_summaries: dict[str, str],
    ) -> str:
        mods = ", ".join(missing_modules)
        return f"{existing_readme.strip()}\n\n## Modules\n\nDocumented modules: {mods}\n"


