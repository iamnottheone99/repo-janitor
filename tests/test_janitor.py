    """Create a temporary git repository with undocumented and untested Python code."""
    repo_dir = tmp_path / "sample_repo"
    repo_dir.mkdir()
    repo = Repo.init(repo_dir)
    with repo.config_writer() as cw:
        cw.set_value("user", "name", "Test Bot")
